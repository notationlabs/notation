import * as durable from "@notation/reconciler/durable";
import {
  createLoggerReconcilerSubscriber,
  type ReconcilerEventEmitter,
  type ResourceRegistry,
} from "@notation/reconciler";
import type { Deployment } from "src/config/deployment";
import { getResourceGraph } from "src/orchestrator/graph";
import {
  loadStateProviderRegistry,
  mergeResourceRegistries,
} from "../resource-registry";
import {
  runDurableWorkflow,
  type NodeDurableRuntime,
} from "../durable-runtime";

export type DeployAppOptions = {
  deployment: Deployment;
  driftDetection?: boolean;
  dryRun?: boolean;
  maxOperationAttempts?: number;
  /**
   * Classes to delete orphaned records through, on top of the classes of
   * the provider packages that state names and of the graph.
   */
  registry?: ResourceRegistry;
  runtime?: NodeDurableRuntime;
  /** Required: the resume handle for this run, generated by the caller. */
  executionId: string;
  databasePath?: string;
  emit?: ReconcilerEventEmitter;
};

export async function deployApp({
  deployment,
  // Defaulted in one place: the reconciler's drift gate treats absent as on.
  driftDetection,
  dryRun = false,
  maxOperationAttempts,
  registry,
  runtime,
  executionId,
  databasePath,
  emit = createLoggerReconcilerSubscriber(),
}: DeployAppOptions): Promise<void> {
  const graph = await getResourceGraph(deployment.entryPoint, {
    app: deployment.app,
    stage: deployment.stage,
  });
  await runDurableWorkflow(
    { deployment, workflowId: "deploy", runtime, databasePath, executionId },
    async function* (step, executionId, runtime) {
      const providerRegistry = yield* loadStateProviderRegistry(
        step,
        runtime.state,
        graph.resources,
        emit,
      );
      yield* durable.deploy(step, {
        executionId,
        resources: graph.resources,
        state: runtime.state,
        registry: mergeResourceRegistries(providerRegistry, registry),
        emit,
        dryRun,
        driftDetection,
        maxOperationAttempts,
      });
    },
  );
}
